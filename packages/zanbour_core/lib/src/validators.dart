/// تحقّق من صحة مدخلات النماذج، برسائل عربية.
///
/// **قاعدة مهمة:** كل قاعدة هنا لها نظير في قاعدة البيانات. التحقق في
/// التطبيق للراحة فقط — يخبر المستخدم بخطئه فوراً بدل انتظار رد الخادم.
/// أما الحماية الفعلية فمن القاعدة، لأن التطبيق يعمل على جهاز المستخدم
/// ولا يمكن الوثوق به.
class Validators {
  Validators._();

  // ---------------------------------------------------------------------------
  // الاسم الثلاثي
  // ---------------------------------------------------------------------------
  static String? fullName(String? v) {
    final s = (v ?? '').trim();
    if (s.isEmpty) return 'الاسم مطلوب';

    // نقسم على أي تتابع فراغات — تماماً كما يفعل مُشغّل قاعدة البيانات
    final parts = s.split(RegExp(r'\s+')).where((p) => p.isNotEmpty).toList();
    if (parts.length < 3) return 'اكتب الاسم الثلاثي كاملاً';
    if (s.length < 8) return 'الاسم قصير جداً';
    if (RegExp(r'[0-9]').hasMatch(s)) return 'الاسم لا يحتوي أرقاماً';
    return null;
  }

  // ---------------------------------------------------------------------------
  // البريد الإلكتروني
  // ---------------------------------------------------------------------------
  static String? email(String? v) {
    final s = (v ?? '').trim();
    if (s.isEmpty) return 'البريد الإلكتروني مطلوب';
    // نمط متساهل عمداً: التحقق القاطع من صحة البريد مستحيل بالتعبير النمطي،
    // والتأكيد الحقيقي يأتي برسالة التفعيل التي لن تصل لبريد خاطئ.
    if (!RegExp(r'^[^@\s]+@[^@\s]+\.[^@\s]{2,}$').hasMatch(s)) {
      return 'صيغة البريد غير صحيحة';
    }
    return null;
  }

  // ---------------------------------------------------------------------------
  // كلمة المرور
  // ---------------------------------------------------------------------------
  static String? password(String? v) {
    final s = v ?? '';
    if (s.isEmpty) return 'كلمة المرور مطلوبة';
    if (s.length < 8) return 'كلمة المرور ٨ أحرف على الأقل';
    if (!RegExp(r'[0-9]').hasMatch(s)) return 'أضف رقماً واحداً على الأقل';
    if (!RegExp(r'[A-Za-zء-ي]').hasMatch(s)) {
      return 'أضف حرفاً واحداً على الأقل';
    }
    return null;
  }

  static String? confirmPassword(String? v, String original) {
    if ((v ?? '').isEmpty) return 'أعد كتابة كلمة المرور';
    if (v != original) return 'كلمتا المرور غير متطابقتين';
    return null;
  }

  // ---------------------------------------------------------------------------
  // رقم الهاتف العراقي
  // ---------------------------------------------------------------------------
  static String? phone(String? v) {
    final digits = (v ?? '').replaceAll(RegExp(r'[^0-9]'), '');
    if (digits.isEmpty) return 'رقم الهاتف مطلوب';
    if (normalizePhone(v) == null) {
      return 'رقم عراقي غير صحيح — مثال: 07701234567';
    }
    return null;
  }

  /// توحيد الرقم إلى صيغة E.164 الدولية.
  ///
  /// يجب أن يطابق منطق `handle_new_user` في قاعدة البيانات حرفياً. لو
  /// اختلفا لقَبِل التطبيق رقماً ترفضه القاعدة، وظهر للمستخدم خطأ غامض
  /// بعد أن اجتاز شاشة التسجيل.
  ///
  /// يقبل: `07701234567` و `9647701234567` و `+9647701234567` و `7701234567`
  static String? normalizePhone(String? v) {
    final d = (v ?? '').replaceAll(RegExp(r'[^0-9]'), '');
    if (RegExp(r'^07[3-9][0-9]{8}$').hasMatch(d)) return '+964${d.substring(1)}';
    if (RegExp(r'^9647[3-9][0-9]{8}$').hasMatch(d)) return '+$d';
    if (RegExp(r'^7[3-9][0-9]{8}$').hasMatch(d)) return '+964$d';
    return null;
  }

  // ---------------------------------------------------------------------------
  // العنوان
  // ---------------------------------------------------------------------------
  static String? address(String? v) {
    final s = (v ?? '').trim();
    if (s.isEmpty) return 'العنوان مطلوب';
    if (s.length < 5) return 'اكتب عنواناً أوضح';
    return null;
  }

  // ---------------------------------------------------------------------------
  // تاريخ الميلاد
  // ---------------------------------------------------------------------------
  /// [minAge] يختلف بين التطبيقين: ١٦ للراكب و ١٨ للسائق.
  static String? birthDate(DateTime? d, {int minAge = 16}) {
    if (d == null) return 'تاريخ الميلاد مطلوب';
    final now = DateTime.now();
    var age = now.year - d.year;
    // لم يبلغ عيد ميلاده هذه السنة بعد
    if (now.month < d.month || (now.month == d.month && now.day < d.day)) {
      age--;
    }
    if (age < minAge) return 'العمر الأدنى $minAge سنة';
    if (age > 100) return 'تاريخ الميلاد غير منطقي';
    return null;
  }
}
