٥٫٥ **مخالفتك لأي مما تقدّم مسؤوليتك وحدك**، وتتحمّل كامل تبعاتها
الإدارية والمدنية والجزائية.


٦ — سلامة الرحلة والركّاب

٦٫١ تتحمّل **المسؤولية الكاملة والمطلقة** عن سلامة الراكب من لحظة صعوده
حتى نزوله، وعن أسلوب قيادتك وسرعتك والتزامك بقواعد المرور.

٦٫٢ تتعهّد بارتداء خوذة واقية مطابقة للمواصفات، وبتوفير خوذة للراكب
حيثما اشترط القانون ذلك.

٦٫٣ يُحظر عليك حظراً مطلقاً قيادة المركبة تحت تأثير كحول أو مخدر أو أي
مؤثر عقلي، أو في حالة إرهاق أو مرض يؤثر في قدرتك على القيادة الآمنة.

٦٫٤ يُحظر عليك نقل عدد من الركّاب يتجاوز ما تسمح به المركبة والقانون،
أو نقل مواد محظورة أو خطرة.

٦٫٥ تتعهّد بمعاملة الركّاب باحترام، والامتناع عن أي إساءة أو تهديد أو
تحرّش أو تمييز، وعن مطالبة الراكب بأي مبلغ يزيد على الأجرة المستحقة.

٦٫٦ **أي حادث أو إصابة أو ضرر يقع أثناء الرحلة أو بسببها هو مسؤوليتك
وحدك**، ولا يتحمّل المشغّل عنه شيئاً بأي وصف.


٧ — التعويض وإبراء الذمّة

٧٫١ توافق على **إبراء ذمّة المشغّل** ومديريه وموظفيه وشركائه من أي
مطالبة أو دعوى أو مسؤولية تنشأ عن نشاطك أو تتصل به.

٧٫٢ وتتعهّد بأن **تعوّض المشغّل وتحميه** من أي مطالبة أو دعوى أو غرامة
أو حكم أو تسوية أو نفقات — بما فيها أتعاب المحاماة — تُرفع عليه أو
تُحمَّل له بسبب:

  (أ) فعلك أو امتناعك أو إهمالك أو تقصيرك؛
  (ب) حادث وقع أثناء رحلة نفّذتها؛
  (ج) مخالفتك لهذه الاتفاقية أو لأي قانون أو تعليمات نافذة؛
  (د) عدم حيازتك ترخيصاً أو تأميناً لازماً؛
  (هـ) ضرر لحق براكب أو بالغير أو بأموالهم بسببك أو بسبب مركبتك.


٨ — الأجرة والعمولة والمحفظة

٨٫١ تقبض الأجرة نقداً من الراكب مباشرةً، وتستحق للمشغّل عمولة عن كل
رحلة تُقيَّد ديناً في محفظتك داخل التطبيق.

٨٫٢ تلتزم بتسديد ما يترتب عليك من عمولات بالوسائل المتاحة في التطبيق.
ويحق للمشغّل إيقاف استقبالك للطلبات عند بلوغ الدين الحد المقرر.

٨٫٣ للمشغّل تعديل نسبة العمولة أو التسعيرة أو آلية الاحتساب في أي وقت،
ويسري التعديل على الرحلات اللاحقة.

٨٫٤ الأرصدة الظاهرة في التطبيق سجلٌّ محاسبي لعلاقتك بالمشغّل، ولا تُعدّ
وديعة مصرفية ولا تستحق عنها فائدة.


٩ — البيانات والموقع

٩٫١ توافق على جمع موقعك الجغرافي وتتبّعه أثناء اتصالك بالخدمة، بما في
ذلك أثناء عمل التطبيق في الخلفية، لأغراض المطابقة وتتبّع الرحلة والسلامة
وتسوية النزاعات.

٩٫٢ توافق على إطلاع الراكب المرتبط برحلتك على بياناتك الضرورية —
كالاسم والصورة وبيانات المركبة ورقم الاتصال — أثناء الرحلة النشطة.

٩٫٣ للمشغّل الاحتفاظ ببياناتك وسجلات رحلاتك للمدة اللازمة نظاماً أو
لتسوية النزاعات أو للاستجابة لطلبات الجهات المختصة.


١٠ — حدود مسؤولية المشغّل

١٠٫١ يُقدَّم التطبيق **«كما هو» و«حسب توافره»** دون أي ضمان صريح أو
ضمني.

١٠٫٢ لا يتحمّل المشغّل أي مسؤولية عن انقطاع الخدمة أو أعطالها أو أخطاء
تقدير المسافة أو الزمن أو الأجرة، ولا عن أي دخل فائت أو فرصة ضائعة.

١٠٫٣ لا يتحمّل المشغّل مسؤولية سلوك الركّاب أو امتناعهم عن الدفع أو أي
ضرر يُلحقونه بك أو بمركبتك.

١٠٫٤ مسؤولية المشغّل الإجمالية تجاهك — إن ثبتت رغم ما تقدّم — لا تتجاوز
مجموع العمولات التي حصّلها منك خلال الشهر السابق لواقعة النزاع.


١١ — إيقاف الحساب وإنهاؤه

١١٫١ للمشغّل — دون إشعار مسبق ودون بيان أسباب ودون تعويض — إيقاف حسابك
مؤقتاً أو إنهاؤه نهائياً، ولا سيّما عند الإخلال بهذه الاتفاقية أو تلقّي
شكاوى تتعلق بالسلامة أو السلوك.

١١٫٢ لك إنهاء استعمالك للخدمة في أي وقت، مع بقاء ما ترتب في ذمّتك من
التزامات مالية.


١٢ — تعديل الاتفاقية

١٢٫١ للمشغّل تعديل هذه الاتفاقية في أي وقت، ويُعدّ استمرارك في استعمال
التطبيق بعد نشر النسخة المعدّلة موافقةً منك عليها.


١٣ — القانون الواجب التطبيق وتسوية النزاعات

١٣٫١ تخضع هذه الاتفاقية وتُفسَّر وفقاً لقوانين جمهورية العراق.

١٣٫٢ يُسعى إلى تسوية أي نزاع ودّياً أولاً، وإن تعذّر اختصّت المحاكم
العراقية المختصة.

١٣٫٣ إذا قُضي ببطلان أي بند أو عدم نفاذه، بقيت سائر البنود نافذةً
بكامل أثرها.


١٤ — إقرار ختامي

بموافقتك على هذه الاتفاقية تُقرّ صراحةً بأنك:

  • قرأتها كاملةً وفهمت مضمونها ولك كامل الأهلية للالتزام بها؛
  • متعاقد مستقل ولست موظفاً لدى المشغّل؛
  • تملك مركبتك وتتحمّل وحدك كل ما يتعلق بها وبسلامتها؛
  • تحوز التراخيص والتأمين اللازمين وتتحمّل تبعات عدم حيازتها؛
  • تتحمّل وحدك المسؤولية الكاملة عن سلامة ركّابك وعن أي حادث؛
