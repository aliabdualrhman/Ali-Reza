-- =============================================================================
-- 0058 — الراكب يسجّل بلا صورة ولا وثائق
-- =============================================================================
-- **قرارُ منتج لا إصلاحُ عطل.**
--
-- كان الراكب يُمنع من استعمال التطبيق حتى يرفع صورةً حية. والحاجز في
-- موضعٍ خاطئ: **الراكب لا ينقل أحداً ولا يقبض مالاً** — يجلس خلف سائقٍ
-- موثَّقٍ مراجَعٍ بعين إنسان، ويدفع نقداً وينزل.
--
-- وثمنُ الحاجز أعلى من عائده بكثير:
--
--   • كل خطوة بين «حمّلتُ التطبيق» و«طلبتُ رحلة» تفقد جزءاً من الناس.
--     وطلبُ صورة وجهٍ من رجلٍ واقفٍ في الشارع يفقد الكثير منهم.
--
--   • ومن يتردّد في تصوير وجهه لتطبيقٍ عمره شهر محقٌّ في تردّده.
--
--   • والصورة لم تكن تُراجَع أصلاً: مُشغّل 0011 يعتمدها تلقائياً بلا
--     أن ينظر إليها أحد. **حاجزٌ يزعج ولا يحمي.**
--
-- **وما يبقى للحماية:** رقم هاتف فريد، وبريد مؤكَّد، وحدّ أدنى للعمر،
-- وقيدٌ يمنع رحلتين متزامنتين، وحظرٌ يوقف المسيء. وهي تكفي لمن يركب.
--
-- **والسائق لا يتغيّر شيءٌ في مساره**: بطاقة وطنية وإجازة سوق وسنوية
-- ومراجعة يدوية. من ينقل الناس يُعرَف من هو.

set search_path = public, extensions;


-- -----------------------------------------------------------------------------
-- ١) الراكب موثَّقٌ منذ لحظة إنشائه
-- -----------------------------------------------------------------------------
-- **لماذا نضبط العلَم بدل أن نحذف فحصه؟** لأن `identity_verified` يُقرأ
-- من مواضع كثيرة — الموجّه، وشاشة الرئيسية، وسياسات RLS، ولوحة المدير.
-- وحذفُ الشرط من كلٍّ منها يترك موضعاً منسياً يمنع راكباً بلا سبب
-- ظاهر. وضبطُه صحيحاً من المصدر يُسقط الحاجز عن كلها دفعةً واحدة.
create or replace function public.verify_rider_by_default()
returns trigger
language plpgsql
security definer
set search_path = public, extensions
as $fn$
begin
  if new.role = 'rider' then
    new.identity_verified := true;
  end if;
  return new;
end;
$fn$;

-- **قبل الإدراج لا بعده.** التعديل على `new` مباشرةً يوفّر تحديثاً
-- ثانياً، ويتجنّب حارس 0007 الذي يمنع تغيير هذا العمود بعد الإنشاء.
drop trigger if exists profiles_verify_rider on public.profiles;
create trigger profiles_verify_rider
  before insert on public.profiles
  for each row execute function public.verify_rider_by_default();


-- -----------------------------------------------------------------------------
-- ٢) الركّاب الحاليون
-- -----------------------------------------------------------------------------
-- **من سجّل ولم يرفع صورته عالقٌ الآن** في شاشة لا مخرج منها. وهم
-- مختبِرونا اليوم.
--
-- ولا نمسّ `deleted_at is not null`: حسابٌ محذوف تُصفَّر بياناته عمداً،
-- وإعادةُ توثيقه تنقض ما فعله الحذف.
--
-- **ونرفع حارس 0007 حول التحديث.** `guard_profile_columns` يمنع تغيير
-- `identity_verified` من أيّ جهة — وهو صحيح: يمنع التطبيق من توثيق
-- نفسه. لكنّ هذا ترحيلٌ لا تطبيق، والقرار قرارنا. وبلا رفعه يفشل
-- الملف بـ42501 بعد أن يكون المُشغّل قد رُكّب — فيعمل للقادمين ويترك
-- الحاضرين معلّقين.
select set_config('app.bypass_guards', 'on', false);

update public.profiles
set identity_verified = true
where role = 'rider'
  and identity_verified = false
  and deleted_at is null;

select set_config('app.bypass_guards', 'off', false);


-- -----------------------------------------------------------------------------
-- ٣) الصورة تبقى ممكنة — اختياريةً
-- -----------------------------------------------------------------------------
-- **لا نحذف المسار، نرفع الإلزام.** من أراد صورةً لملفه يرفعها من
-- «حسابي»، ومُشغّل 0019 يجعلها صورته كما كان. والفرق أن أحداً لم يعد
-- يُمنع من الركوب حتى يفعل.
--
-- ووثائق الركّاب المرفوعة سلفاً تبقى كما هي: حذفها يمحو ما رفعه الناس
-- بأنفسهم، ولا موجب له.


-- -----------------------------------------------------------------------------
-- فحص بعد التطبيق — يجب أن يكون «معلَّقون» صفراً
-- -----------------------------------------------------------------------------
select
  count(*) filter (where identity_verified)     as "ركّاب يستطيعون الاستعمال",
  count(*) filter (where not identity_verified) as "معلَّقون"
from public.profiles
where role = 'rider' and deleted_at is null;
