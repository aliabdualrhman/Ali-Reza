-- =============================================================================
-- 0038 — حدود منطقة الخدمة للبحث عن العناوين
-- =============================================================================
-- **العَرَض.** راكب في الناصرية يبحث عن «الكرادة» فتأتيه نتائج من بغداد،
-- ويبحث عن «شارع النهر» فتزاحمه أسماء من البصرة والموصل. يختار واحدة
-- بحسن نية، فيطلب رحلة إلى مدينة أخرى.
--
-- **السبب.** البحث مقيّد بـ`countrycode:iq` وحدها — أي بالعراق كله.
-- والتقييد بالدولة كان صواباً حين أضفناه (بدونه تأتي نتائج من مصر
-- والسعودية)، لكنه لم يعد كافياً.
--
-- **الحل: نُعطي البحث مستطيل المنطقة التي يقف فيها صاحبه.** والمستطيل
-- يأتي من `pricing_zones` نفسها — أي من المناطق التي يفعّلها المدير من
-- اللوحة. فإن أطفأ المدير محافظةً، توقّف البحث فيها كما توقّفت الرحلات.
-- مصدر واحد للحقيقة بدل قائمة مدن ثانية في الكود تنسى أن تُحدَّث.
--
-- **ولماذا تمرّ بـ`zone_for_point`؟** لئلا نكرّر منطق الاختيار. هي التي
-- تعرف المنطقة المفعّلة، وهي التي تعرف وضع المراجعة (٠٠٣٧) فتردّ
-- المنطقة الاحتياطية لمن هو خارج التغطية. فيرث البحث السلوكين معاً بلا
-- سطر إضافي: مراجع جوجل في كاليفورنيا يبحث فيجد أماكن الناصرية،
-- ويستطيع طلب رحلة.

set search_path = public, extensions;


-- -----------------------------------------------------------------------------
-- حدود المنطقة التي تقع فيها نقطة
-- -----------------------------------------------------------------------------
-- تعيد صفراً واحداً أو لا شيء. **لا شيء ليست خطأً**: تعني أن صاحبها خارج
-- كل تغطية ووضع المراجعة مطفأ — وحينها يعود التطبيق إلى التقييد بالدولة
-- وحدها، فيبحث ولا يُمنع.
create or replace function public.zone_bbox(p_point geography)
returns table (
  min_lon double precision,
  min_lat double precision,
  max_lon double precision,
  max_lat double precision,
  city_name_ar text
)
language sql
stable
security definer
set search_path = public, extensions
as $fn$
  select
    st_xmin(box), st_ymin(box), st_xmax(box), st_ymax(box), z.city_name_ar
  from public.pricing_zones z
  cross join lateral (select z.boundary::geometry::box2d as box) b
  where z.id = public.zone_for_point(p_point);
$fn$;


revoke all on function public.zone_bbox(geography) from public, anon;
grant execute on function public.zone_bbox(geography) to authenticated;


-- -----------------------------------------------------------------------------
-- فحص بعد التطبيق — نقطة في وسط الناصرية
-- -----------------------------------------------------------------------------
select * from public.zone_bbox(
  st_setsrid(st_makepoint(46.2575, 31.0439), 4326)::geography
);
