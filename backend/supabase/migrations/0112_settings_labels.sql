-- =============================================================================
-- 0112 — تسمية إعدادين ظهرا بمفتاحهما الإنجليزي
-- =============================================================================
-- صفحة الإعدادات تعرض كل صفٍّ في `public_settings` بعموده `label`، وتسقط
-- إلى المفتاح إن كان فارغاً. وإعدادان أُضيفا اليوم بلا تسمية:
--
--   delivery_min_fee_stoota_iqd   (0105)
--   incentives_max_active         (0108)
--
-- فيراهما المدير سطرين إنجليزيين بين عشرين سطراً عربياً، ولا يدري ما
-- يفعل أحدهما.

set search_path = public, extensions;

update public.public_settings
set label = 'طلب المندوب — أقل سعر توصيل بالستوتة'
where key = 'delivery_min_fee_stoota_iqd' and coalesce(label, '') = '';

update public.public_settings
set label = 'الحوافز — كم حافزاً يفعّل السائق في وقتٍ واحد'
where key = 'incentives_max_active' and coalesce(label, '') = '';


-- -----------------------------------------------------------------------------
-- فحص بعد التطبيق — يجب ألا يبقى إعدادٌ بلا تسمية
-- -----------------------------------------------------------------------------
select count(*) as "إعدادات بلا تسمية (٠)"
from public.public_settings
where coalesce(label, '') = '';
