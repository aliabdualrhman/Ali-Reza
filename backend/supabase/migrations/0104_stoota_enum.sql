-- **هذا الملف سطرٌ واحد، ويُطبَّق وحده.**
--
-- بوستغرس لا يسمح باستعمال قيمة تعداد جديدة في المعاملة التي أضافتها:
--
--     ERROR: unsafe use of new value "stoota" of enum type vehicle_kind
--
-- ومحرّر SQL في Supabase يُشغّل الملف كمعاملةٍ واحدة. فلو وُضع هذا السطر
-- مع دوالّ 0105 التي تذكر `'stoota'` لفشل الملف كلّه.
--
-- **والستوتة ليست دراجةً أكبر.** السائق الذي يسجّل بها لا يحمل ركّاباً
-- ولا يتسوّق: طلبات المتاجر وحدها، وحين يطلب المتجر ستوتةً بالذات.
-- وذلك كلّه في 0105.

alter type public.vehicle_kind add value if not exists 'stoota';


-- فحص بعد التطبيق — يجب أن يظهر: bike,tuktuk,stoota
select string_agg(e.enumlabel, ',' order by e.enumsortorder) as "أنواع المركبات"
from pg_type t
join pg_enum e on e.enumtypid = t.oid
where t.typname = 'vehicle_kind';
