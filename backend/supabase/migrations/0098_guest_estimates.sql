-- =============================================================================
-- 0098 — الضيف يرى الأجرة التقديرية للتسوّق كما يراها للرحلة
-- =============================================================================
-- **الدخول كضيف بلا جلسة** (انظر `guest_mode.dart`): يعمل التطبيق بدور
-- `anon` وحده. وتقدير الرحلة مفتوحٌ له منذ البداية (`estimate_trip`،
-- `estimate_multi_trip`)، أمّا تقدير التسوّق فأُغلق عليه — فيرى الضيف
-- أجرة الرحلة ولا يرى أجرة التسوّق، وهي أول ما يسأل عنه.
--
-- **وكلاهما حسابٌ محض.** لا يقرأ بيانات أحد ولا يكتب شيئاً: إحداثياتٌ
-- ومسافةٌ تدخل، ورقمٌ يخرج. ففتحهما لـ`anon` لا يكشف شيئاً.
--
--   estimate_shopping — أجرة طلب التسوّق
--   zone_bbox         — حدود منطقة الخدمة، يقيّد بها البحث في الخريطة
--
-- **وما لا يُفتح:** `check_coupon` (الكوبون مربوطٌ بحساب)، وكل ما يطلب
-- أو يكتب. تلك تبقى لـ`authenticated`، والتطبيق يدعو الضيف للتسجيل
-- قبل أن يصل إليها.

grant execute on function public.estimate_shopping(
  double precision, double precision, integer, integer
) to anon;

grant execute on function public.zone_bbox(extensions.geography) to anon;


-- -----------------------------------------------------------------------------
-- فحص بعد التطبيق — يجب أن يعود السطران بـ true
-- -----------------------------------------------------------------------------
select p.proname,
       has_function_privilege('anon', p.oid, 'execute') as "مفتوح للضيف"
from pg_proc p
where p.pronamespace = 'public'::regnamespace
  and p.proname in ('estimate_shopping', 'zone_bbox');
