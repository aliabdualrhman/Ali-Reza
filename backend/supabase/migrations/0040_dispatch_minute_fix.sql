-- =============================================================================
-- 0040 — محرك التوزيع متوقف منذ 0021: `commit` في إجراء `security definer`
-- =============================================================================
-- **العَرَض.** الراكب يطلب رحلة ولا سائق متصل. يتصل سائق بعد ثوانٍ —
-- ولا يصله شيء. يبقى الراكب يبحث حتى تنتهي المهلة و«لا يوجد سائقون».
--
-- وهذه ليست حالة نادرة بل **الحالة الشائعة** في أي مدينة قبل أن يمتلئ
-- أسطولها: أول من يطلب يسبق أول من يتصل.
--
-- **السبب.** المهمة المجدولة تعمل كل دقيقة بأمانة — **وتفشل في كل مرة**:
--
--     status: failed  (١٠ من ١٠)
--     ERROR: invalid transaction termination
--
-- و0021 حوّل `dispatch_minute` من دالة إلى إجراء ليستطيع `commit` في
-- منتصفه — وكان محقاً في العلّة: المعاملة الممتدة دقيقةً تحمل أقفالاً
-- تمنع الراكب من الإلغاء والسائق من القبول. لكنه أبقى `security definer`
-- على الإجراء.
--
-- **وPostgreSQL يمنع التحكم بالمعاملات داخل إجراء `security definer`
-- منعاً باتاً.** فيفشل عند أول `commit`، وقبله لا شيء — لأن `commit`
-- تأتي بعد أول `dispatch_tick` مباشرة، فتُلغى المعاملة كلها بما فيها
-- العروض التي أُنشئت.
--
-- **النتيجة: محرك التوزيع لم يوزّع عرضاً واحداً منذ تطبيق 0021.** ما كان
-- يعمل هو التوزيع اللحظي عند إنشاء الرحلة وحده — ولهذا بدا النظام سليماً
-- ما دام السائق متصلاً **قبل** الطلب.
--
-- **الحل: إجراء عارٍ من كل صفة — لا `security definer` ولا `set`.**
--
-- **والصفتان تُمنعان للسبب نفسه، وهذا ما كلّفنا محاولةً ضائعة.** جرّبنا
-- نزع `security definer` وحدها فبقي الفشل حرفياً كما هو: PostgreSQL
-- يستدعي أي إجراء يحمل إحدى الصفتين عبر غلاف يحفظ السياق ويستعيده عند
-- الخروج، وذلك الغلاف يجعل السياق **ذرّياً** فيُمنع `commit`. نزعُ
-- واحدة وإبقاء الأخرى لا يغيّر شيئاً.
--
-- ولا نخسر بنزعهما:
--
--   • الصلاحية: كل العمل ذي الامتياز في `dispatch_tick` وهي
--     `security definer` بنفسها. الإجراء غلافُ توقيتٍ لا غلافُ صلاحية.
--   • مسار البحث: ينادي `public.dispatch_tick()` بالاسم الكامل،
--     و`pg_sleep` في `pg_catalog` المتاح دائماً. لا حاجة إليه أصلاً.
--
-- والعكس — إبقاء الصفات وحذف `commit` — يعيد العطل الذي أصلحه 0021:
-- معاملةٌ ممتدة دقيقةً تحمل أقفالاً تمنع الراكب من الإلغاء والسائق من
-- القبول.

set search_path = public, extensions;


-- -----------------------------------------------------------------------------
-- ١) الإجراء عارياً — بلا `security definer` وبلا `set`
-- -----------------------------------------------------------------------------
-- **نحذف ثم نُنشئ.** `create or replace` لا يغيّر صفات الأمان على إجراء
-- قائم، فتبقى النسخة المعطوبة وتظنّ أنك أصلحتها.
drop procedure if exists public.dispatch_minute();

create procedure public.dispatch_minute()
language plpgsql
as $fn$
declare
  i integer;
begin
  for i in 1..12 loop
    perform public.dispatch_tick();

    -- الإفلات من المعاملة يُطلق كل أقفال هذه النبضة، فيجد الراكبُ رحلته
    -- حرّةً ليلغيها والسائقُ ليقبلها.
    commit;

    if i < 12 then perform pg_sleep(5); end if;
  end loop;
end;
$fn$;


-- -----------------------------------------------------------------------------
-- ٢) الجدولة
-- -----------------------------------------------------------------------------
-- `call` لا `select`: الإجراء لا يعمل داخل استعلام، والتحكم بالمعاملة
-- لا يُسمح به إلا من المستوى الأعلى.
select cron.unschedule('zanbour-dispatch')
where exists (select 1 from cron.job where jobname = 'zanbour-dispatch');

select cron.schedule(
  'zanbour-dispatch',
  '* * * * *',
  $cron$ call public.dispatch_minute(); $cron$
);


-- -----------------------------------------------------------------------------
-- ٣) نبضة فورية
-- -----------------------------------------------------------------------------
-- لا ننتظر الدقيقة القادمة: أي رحلة تبحث الآن تُخدَم في هذه اللحظة.
select public.dispatch_tick();


-- -----------------------------------------------------------------------------
-- فحص بعد التطبيق — انتظر دقيقتين ثم شغّله
-- -----------------------------------------------------------------------------
-- **`succeeded` هي المطلوبة.** الجدولة المفعّلة لا تعني شيئاً وحدها —
-- كانت `active = true` طوال الوقت والمهمة تفشل في كل نبضة. الحالة هي
-- الحقيقة لا الجدولة.
select
  start_time                        as "وقت التشغيل",
  status                            as "الحالة",
  coalesce(return_message, '—')     as "الرسالة"
from cron.job_run_details
where jobid = (select jobid from cron.job where jobname = 'zanbour-dispatch')
order by start_time desc
limit 5;
