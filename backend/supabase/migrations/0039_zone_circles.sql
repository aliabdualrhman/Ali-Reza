-- =============================================================================
-- 0039 — مناطق الخدمة: دوائر حول المدن بدل مستطيلات على المحافظات
-- =============================================================================
-- **العَرَض.** راكب في قرية على بُعد ٢٥ كم من الناصرية يطلب رحلة، فتُقبل
-- ولا يجد سائقاً. والبحث عن العناوين يعرض أماكن في الصحراء. والبثّ يمسح
-- مساحةً فارغة قبل أن يصل إلى من هم في المدينة.
--
-- **السبب.** حدود ٠٠١٢ **مستطيلات** رُسمت بأربع نقاط حول كل مدينة،
-- ووُسّعت ١٥٪ احتياطاً. والاحتياط تراكم:
--
--     الديوانية   ٦٬٠٠١ كم²   ← محافظة كاملة
--     الكوت       ٥٬٠٠٧ كم²
--     الناصرية    ١٬٨٢٥ كم²   ← والمدينة نفسها ~١٠٠ كم²
--     ─────────────────────
--     المجموع    ٣٤٬٢٩٥ كم²   لثمانية عشر مدينة
--
-- **ولماذا الدائرة؟** لأن خدمتنا تُقاس بمدى ما تصله الدراجة من مركز
-- المدينة، لا بحدود إدارية. المستطيل شكلٌ ورثناه من طريقة الرسم لا من
-- طبيعة الخدمة — وهو يمدّ أطرافه في أربع زوايا لا يسكنها أحد.
--
-- **ولماذا لا حدود OSM الحقيقية؟** جرّبناها: لا توجد مضلعات إدارية
-- للمدن العراقية في OpenStreetMap، تعيد نقطةً فقط. فالدائرة ليست
-- تبسيطاً اضطرارياً بل أفضل ما هو متاح — وأصدق نموذجاً على أي حال.
--
-- **النتيجة:** ٣٤٬٢٩٥ كم² ← ٦٬٣٦٨ كم². انكماش ٨١٪ بلا خسارة تغطية
-- عمرانية واحدة.
--
-- ونصف القطر بحسب حجم المدينة: بغداد ٢٠ كم، والبصرة والموصل وأربيل ١٢،
-- ومراكز المحافظات ٨-١٠. **قابل للتعديل بتشغيل هذا الملف من جديد بعد
-- تغيير الأرقام** — `st_buffer` تحسبها من المركز في كل مرة.

set search_path = public, extensions;


-- -----------------------------------------------------------------------------
-- المراكز وأنصاف الأقطار
-- -----------------------------------------------------------------------------
-- المراكز من OpenStreetMap. المدن غير المذكورة هنا لا تُمسّ.
with centers (city_name, lon, lat, radius_m) as (values
  ('Amarah',        47.1450, 31.8356,  9000),
  ('Baghdad',       44.3661, 33.3152, 20000),
  ('Baqubah',       44.6440, 33.7500,  9000),
  ('Basra',         47.7804, 30.5085, 12000),
  ('Diwaniyah',     44.9250, 31.9924,  9000),
  ('Duhok',         42.9880, 36.8670,  9000),
  ('Erbil',         44.0092, 36.1911, 12000),
  ('Hillah',        44.4197, 32.4637,  9000),
  ('Karbala',       44.0249, 32.6160, 10000),
  ('Kirkuk',        44.3922, 35.4681, 10000),
  ('Kut',           45.8181, 32.5128,  9000),
  ('Mosul',         43.1189, 36.3350, 12000),
  ('Najaf',         44.3350, 32.0000, 10000),
  ('Nasiriyah',     46.2570, 31.0440, 10000),
  ('Ramadi',        43.3080, 33.4200,  9000),
  ('Samawah',       45.2810, 31.3300,  8000),
  ('Sulaymaniyah',  45.4408, 35.5613, 10000),
  ('Tikrit',        43.6800, 34.6100,  8000)
)
update public.pricing_zones z
set boundary = st_buffer(
      st_setsrid(st_makepoint(c.lon, c.lat), 4326)::geography,
      c.radius_m
    )
from centers c
where z.city_name = c.city_name;


-- -----------------------------------------------------------------------------
-- فحص بعد التطبيق
-- -----------------------------------------------------------------------------
-- **المساحة تُقرأ لا تُفترض.** خطأ في المركز أو نصف القطر لا يرمي
-- استثناءً — يُنتج منطقةً في مكان خاطئ تعمل بصمت. الرقم يكشفه.
select
  z.city_name_ar                                    as "المدينة",
  round((st_area(z.boundary) / 1000000)::numeric)    as "المساحة كم²",
  round(st_y(st_centroid(z.boundary::geometry))::numeric, 3) as "خط العرض",
  round(st_x(st_centroid(z.boundary::geometry))::numeric, 3) as "خط الطول",
  z.is_active                                        as "مفعّلة"
from public.pricing_zones z
order by st_area(z.boundary) desc;
